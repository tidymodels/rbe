# Build `catboost_params`, the list of valid catboost training parameters, and
# write it into the generated block at the end of `R/arguments.R`.
#
# The R package has no function that lists its parameters, and the
# `catboost.train()` help page is incomplete (e.g., it omits
# `final_ctr_computation_mode`). The full reference lives in the catboost repo
# as markdown files; each parameter is a `## name {#name}` heading followed by
# an optional `_Alias:_` or `_Aliases:_` line. The names in the installed R help
# page are added since a few R-only parameters are not in the markdown files.
#
# Re-run this script when catboost adds parameters.

doc_files <- c(
  "common",
  "ctr",
  "input",
  "multiclassification",
  "output",
  "overfitting-detection",
  "performance",
  "processing-unit",
  "quantization",
  "text-processing",
  "visualization"
)

repo <- "catboost/catboost"
doc_dir <- "catboost/docs/en/references/training-parameters"

commit <- jsonlite::fromJSON(
  paste0("https://api.github.com/repos/", repo, "/commits/master")
)
sha <- commit$sha
commit_date <- commit$commit$committer$date

parse_doc <- function(file) {
  url <- paste0(
    "https://raw.githubusercontent.com/",
    repo,
    "/",
    sha,
    "/",
    doc_dir,
    "/",
    file,
    ".md"
  )
  lines <- readLines(url, warn = FALSE)

  heading_rx <- "^## ([a-z][a-z0-9_]*) \\{#"
  is_heading <- grepl(heading_rx, lines)
  # Any `## ` line ends the current parameter's section
  is_section <- grepl("^## ", lines)
  section_id <- cumsum(is_section)

  res <- list()
  for (i in which(is_heading)) {
    param <- sub(paste0(heading_rx, ".*$"), "\\1", lines[i])
    in_section <- which(section_id == section_id[i])
    alias_lines <- grep("^_Alias(es)?:_", lines[in_section], value = TRUE)
    aliases <- regmatches(alias_lines, gregexpr("`[^`]+`", alias_lines))
    aliases <- gsub("`", "", unlist(aliases))
    res[[length(res) + 1]] <- data.frame(
      name = c(param, aliases),
      param = param
    )
  }
  do.call(rbind, res)
}

from_docs <- do.call(rbind, lapply(doc_files, parse_doc))

rd <- tools::Rd_db("catboost")[["catboost.train.Rd"]]
rd_txt <- capture.output(
  tools::Rd2txt(rd, options = list(underline_titles = FALSE))
)
rd_params <- grep("^ {12}• [a-z][a-z0-9_]*$", rd_txt, value = TRUE)
rd_params <- trimws(sub("^ {12}• ", "", rd_params))
from_rd <- data.frame(name = rd_params, param = rd_params)

catboost_params <- rbind(from_docs, from_rd)
catboost_params <- catboost_params[!duplicated(catboost_params$name), ]
catboost_params <- catboost_params[
  order(catboost_params$param, catboost_params$name != catboost_params$param),
]
rownames(catboost_params) <- NULL

quote_vec <- function(x) {
  paste0("    \"", x, "\"", collapse = ",\n")
}

begin_marker <- paste0(
  "# BEGIN GENERATED by data-raw/catboost-params.R: do not edit by hand"
)
end_marker <- "# END GENERATED"

generated <- c(
  begin_marker,
  paste0(
    "# Source: https://github.com/",
    repo,
    "/tree/",
    sha,
    "/",
    doc_dir
  ),
  paste0("# Commit date: ", commit_date),
  paste0(
    "# catboost R package version: ",
    utils::packageVersion("catboost")
  ),
  "",
  "# `name` is a parameter or one of its aliases; `param` is the main name.",
  "catboost_params <- data.frame(",
  "  name = c(",
  quote_vec(catboost_params$name),
  "  ),",
  "  param = c(",
  quote_vec(catboost_params$param),
  "  )",
  ")",
  end_marker
)

# Replace only the generated block so the hand-written code is kept
target <- "R/arguments.R"
existing <- readLines(target)
begin <- which(existing == begin_marker)
end <- which(existing == end_marker)
if (length(begin) != 1 || length(end) != 1 || end < begin) {
  cli::cli_abort("Could not find the generated block in {.file {target}}.")
}
out <- c(
  existing[seq_len(begin - 1)],
  generated,
  existing[-seq_len(end)]
)
writeLines(out, target)
